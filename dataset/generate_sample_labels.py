#!/usr/bin/env python3
"""
generate_sample_labels.py
--------------------------
Creates realistic sample YOLO annotation .txt files for all 12 ASL classes.
Used to demonstrate the annotation format and populate the labels/ directory
with examples that can be reviewed and validated.

Run once during project setup:
    python dataset/generate_sample_labels.py
"""

import os
import random
from pathlib import Path

random.seed(42)

# class_id: (x_center_mean, y_center_mean, width_mean, height_mean, x_std, y_std, w_std, h_std)
CLASS_BBOX_PARAMS = {
    0:  (0.500, 0.440, 0.360, 0.520, 0.035, 0.030, 0.025, 0.030),  # A - compact fist
    1:  (0.500, 0.420, 0.310, 0.570, 0.030, 0.025, 0.020, 0.030),  # B - tall narrow
    2:  (0.500, 0.450, 0.380, 0.490, 0.035, 0.030, 0.025, 0.025),  # C - near-square
    3:  (0.500, 0.420, 0.300, 0.540, 0.030, 0.025, 0.020, 0.030),  # D - tall (index up)
    4:  (0.500, 0.460, 0.340, 0.480, 0.035, 0.030, 0.025, 0.025),  # E - compact
    5:  (0.500, 0.430, 0.370, 0.510, 0.035, 0.030, 0.025, 0.030),  # F - medium
    6:  (0.500, 0.450, 0.410, 0.420, 0.040, 0.030, 0.030, 0.025),  # G - wide horizontal
    7:  (0.500, 0.450, 0.420, 0.420, 0.040, 0.030, 0.030, 0.025),  # H - wide horizontal
    8:  (0.500, 0.410, 0.290, 0.560, 0.030, 0.025, 0.020, 0.030),  # I - tall narrow
    9:  (0.500, 0.420, 0.290, 0.550, 0.030, 0.025, 0.020, 0.030),  # J - tall (dynamic)
    10: (0.500, 0.430, 0.350, 0.530, 0.035, 0.030, 0.025, 0.030),  # K - tall medium
    11: (0.500, 0.440, 0.400, 0.530, 0.040, 0.030, 0.030, 0.030),  # L - wide tall
}

ASL_CLASSES = ["A", "B", "C", "D", "E", "F", "G", "H", "I", "J", "K", "L"]


def clamp(v, lo=0.01, hi=0.99):
    return max(lo, min(hi, v))


def generate_annotation(class_id: int) -> str:
    xc_m, yc_m, w_m, h_m, xc_s, yc_s, w_s, h_s = CLASS_BBOX_PARAMS[class_id]
    xc = clamp(random.gauss(xc_m, xc_s))
    yc = clamp(random.gauss(yc_m, yc_s))
    w  = clamp(random.gauss(w_m,  w_s),  lo=0.10, hi=0.80)
    h  = clamp(random.gauss(h_m,  h_s),  lo=0.15, hi=0.90)
    return f"{class_id} {xc:.4f} {yc:.4f} {w:.4f} {h:.4f}"


def populate_labels(n_per_class: int = 5):
    """
    Write n_per_class sample label files per class into each split directory.
    In a real project these would be generated by LabelImg / Roboflow.
    """
    for split in ["train", "valid", "test"]:
        n = n_per_class if split == "train" else max(1, n_per_class // 3)
        out_dir = Path(f"dataset/labels/{split}")
        out_dir.mkdir(parents=True, exist_ok=True)

        for cls_idx, cls_name in enumerate(ASL_CLASSES):
            for i in range(n):
                annotation = generate_annotation(cls_idx)
                filename = out_dir / f"{cls_name}_{i+1:04d}.txt"
                filename.write_text(annotation + "\n")

    print(f"[INFO] Sample label files written to dataset/labels/")
    print(f"       Replace these with real annotations before training.")


if __name__ == "__main__":
    populate_labels(n_per_class=5)
